export const defaultClientId = "default";

export function resolveClientId(clientId) {
  if (!clientId) return defaultClientId;

  if (clientThemes[clientId]) return clientId;

  const normalized = Object.keys(clientThemes).find((key) => {
    const theme = clientThemes[key];
    return (
      theme?.id === clientId ||
      theme?.name === clientId ||
      theme?.label === clientId
    );
  });

  return normalized || defaultClientId;
}

export function getClientTheme(clientId = defaultClientId) {
  return (
    clientThemes[resolveClientId(clientId)] || clientThemes[defaultClientId]
  );
}

export function getClientThemeOptions() {
  return Object.entries(clientThemes).map(([key, theme]) => ({
    value: key,
    label: theme.label,
    name: theme.name,
  }));
}
